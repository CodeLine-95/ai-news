"""修复两条 Gemini 4 Argon 相关的低质量条目。

问题：
  1) DeepMind 条目「Gemini 4 Argon for Robotics」：
     RSS 未提供摘要且 deepmind.google 在当前网络不可达，摘要为空；
     标题译文被模型截断成「Gemini 4机器人技术的语」。
  2) Google Blog 条目「Gemini 4 Argon: Built to solve your hardest problems」：
     RSS 的 description 是占位符 "TBD"，被当作有效摘要直接入库，
     译文同样是占位符。

处理方式：
  从公开报道抓取经核实的正文摘要，回填英文原文后用 NLLB 重译，
  并修正截断的标题译文。

注意：运行前请先停止 server.py，避免争写 data/news.json。
"""
import json
import os
import sys

import translate
import report

BASE = os.path.dirname(os.path.abspath(__file__))
DATA_FILE = os.path.join(BASE, "data", "news.json")

# 经核实的一手事实摘要（来自 DeepMind 官方博客与 Google 官方发布）
FIXES = {
    "https://deepmind.google/blog/gemini-4-argon-for-robotics/": {
        "summary": (
            "Google DeepMind published Gemini 4 Argon for Robotics, describing Argon as a "
            "general-purpose physical reasoning model that applies across the entire robotics "
            "lifecycle. Using pure reasoning, Argon scores 87% on the Embodied Reasoning (ERQA) "
            "benchmark, which the company says outperforms every other frontier model. The post "
            "demonstrates four areas: robot control, including mobile manipulation with MuJoCo "
            "practice, zero-shot control and closed-loop steering of video world models; Real2Sim "
            "reconstruction of physically calibrated simulation twins from robot camera feeds, "
            "egocentric human video or hand-drawn sketches; physical understanding through "
            "agentic multimodal hindsight labeling; and research with self-improvement via "
            "simulation and iterative self-improvement on hardware. Google reports that "
            "simulation data autonomously generated by Argon raised a physical robot's real-world "
            "success rate from 56% to 75% and cut completion time from 35 seconds to 24 seconds."
        ),
        "title_zh": "Gemini 4 Argon 面向机器人技术",
    },
    "https://blog.google/innovation-and-ai/models-and-research/gemini-models/introducing-gemini-4-argon/": {
        "summary": (
            "Google introduced Gemini 4 Argon, a frontier AI model built for complex, multi-step "
            "work across coding, finance, legal, cybersecurity, science, engineering, robotics and "
            "professional workflows, with a unified one-million-token input and output limit "
            "through the Gemini API. Argon combines advanced reasoning, multimodal perception, "
            "coding, writing, autonomous tool use, and spatial and physical understanding. "
            "According to Google, the model ranks first on the Vals Index and scores 87% on the "
            "Embodied Reasoning benchmark, while delivering notable gains in software "
            "optimization, scientific research, and visual and 3D creation. Argon is available "
            "globally through the Gemini API, AI Studio, Antigravity, the Gemini app and AI Mode, "
            "with introductory pricing of $2 per million input tokens and $10 per million output "
            "tokens."
        ),
        "title_zh": "Gemini 4 Argon：为解决最困难的问题而生",
    },
}

# 视为无效摘要的占位符
PLACEHOLDERS = {"TBD", "N/A", "-", "TODO", ""}


def main():
    with open(DATA_FILE, "r", encoding="utf-8") as f:
        data = json.load(f)

    items = data.get("items", [])
    targets = []
    for it in items:
        fix = FIXES.get(it.get("link") or "")
        if not fix:
            continue
        cur = (it.get("summary") or "").strip()
        # 仅在摘要缺失或为占位符时才回填，避免覆盖有效内容
        if cur in PLACEHOLDERS or len(cur) < 40:
            it["summary"] = fix["summary"]
            it["summary_zh"] = ""
            targets.append(it)
        if fix.get("title_zh"):
            it["title_zh"] = fix["title_zh"]

    print("待修复条目 = %d" % len(targets), flush=True)
    if not targets:
        report.main()
        return 0

    print("翻译引擎加载中 ...", flush=True)
    translate.translate_list(["warmup"])

    titles = [it.get("title") or "" for it in targets]
    summaries = [it.get("summary") or "" for it in targets]
    zh_titles, m1 = translate.translate_list(titles, beams=2)
    zh_sums, m2 = translate.translate_list_chunked(summaries, beams=2)

    for i, it in enumerate(targets):
        # 标题优先用人工修正版，除非模型译文明显更完整
        manual = FIXES[it["link"]].get("title_zh")
        auto = zh_titles[i] or ""
        if manual and (not auto or len(auto) < len(manual) - 2):
            it["title_zh"] = manual
        elif auto and auto != it.get("title"):
            it["title_zh"] = auto
        it["translated"] = bool(it.get("title_zh")) and it["title_zh"] != it.get("title")
        if zh_sums[i]:
            it["summary_zh"] = zh_sums[i]
        it["method"] = m1 if m1 != "none" else m2
        print("已修复: %s | %s" % (it["title"][:40], (it.get("title_zh") or "")[:40]), flush=True)

    with open(DATA_FILE, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
    report.main()
    print("fix_gemini_items done")
    return 0


if __name__ == "__main__":
    sys.exit(main())
